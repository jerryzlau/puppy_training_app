#!/usr/bin/env node
// Builds src/course-manifest.ts from content/course/week-*/*.mdx
// Validates: unique slugs, 3-5 tasks per lesson, frontmatter completeness.
import fs from "node:fs";
import path from "node:path";
import url from "node:url";
import matter from "gray-matter";

const __dirname = path.dirname(url.fileURLToPath(import.meta.url));
const contentDir = path.resolve(__dirname, "../../../content/course");
const outFile = path.resolve(__dirname, "../src/course-manifest.ts");

const WEEK_META = {
  1: { theme: "homecoming", month: 1 },
  2: { theme: "trust & name", month: 1 },
  3: { theme: "potty & bite", month: 1 },
  4: { theme: "social butterfly", month: 1 },
  5: { theme: "leash — tiny dog edition", month: 2 },
  6: { theme: "core cues", month: 2 },
  7: { theme: "impulse control", month: 2 },
  8: { theme: "home alone", month: 2 },
  9: { theme: "recall for real", month: 3 },
  10: { theme: "city dog", month: 3 },
  11: { theme: "cooperative care", month: 3 },
  12: { theme: "graduation", month: 3 },
  13: { theme: "the teenager arrives", month: 4 },
  14: { theme: "recall — the sequel", month: 4 },
  15: { theme: "leash manners 2.0", month: 4 },
  16: { theme: "brain games", month: 4 },
  17: { theme: "heel & fancy footwork", month: 5 },
  18: { theme: "distance & duration", month: 5 },
  19: { theme: "the trick portfolio", month: 5 },
  20: { theme: "spa mastery", month: 5 },
  21: { theme: "adventure dog", month: 6 },
  22: { theme: "travel & sleepovers", month: 6 },
  23: { theme: "good citizen", month: 6 },
  24: { theme: "graduation ii — with honors", month: 6 },
};

if (!fs.existsSync(contentDir)) {
  console.error(`content dir not found: ${contentDir}`);
  process.exit(1);
}

const errors = [];
const slugs = new Set();
const weeks = [];

const weekDirs = fs
  .readdirSync(contentDir)
  .filter((d) => /^week-\d{2}$/.test(d))
  .sort();

for (const dir of weekDirs) {
  const weekNum = parseInt(dir.slice(5), 10);
  const meta = WEEK_META[weekNum];
  if (!meta) {
    errors.push(`unknown week dir ${dir}`);
    continue;
  }
  const lessons = [];
  const files = fs
    .readdirSync(path.join(contentDir, dir))
    .filter((f) => f.endsWith(".mdx"))
    .sort();
  for (const file of files) {
    const raw = fs.readFileSync(path.join(contentDir, dir, file), "utf8");
    const { data, content } = matter(raw);
    const slug = data.slug;
    if (!slug || typeof slug !== "string") {
      errors.push(`${dir}/${file}: missing slug`);
      continue;
    }
    if (slug !== `${dir}/${file.replace(/\.mdx$/, "")}`) {
      errors.push(`${dir}/${file}: slug "${slug}" must match path "${dir}/${file.replace(/\.mdx$/, "")}"`);
    }
    if (slugs.has(slug)) errors.push(`duplicate slug: ${slug}`);
    slugs.add(slug);
    if (data.week !== weekNum) errors.push(`${slug}: week ${data.week} != dir ${weekNum}`);
    if (!data.title) errors.push(`${slug}: missing title`);
    if (typeof data.order !== "number") errors.push(`${slug}: missing order`);
    const tasks = Array.isArray(data.tasks) ? data.tasks : [];
    if (tasks.length < 3 || tasks.length > 5)
      errors.push(`${slug}: has ${tasks.length} tasks (need 3-5)`);
    const taskIds = new Set();
    const fullTasks = tasks.map((t, i) => {
      const id = t.id || `task-${i + 1}`;
      if (taskIds.has(id)) errors.push(`${slug}: duplicate task id ${id}`);
      taskIds.add(id);
      if (!t.text) errors.push(`${slug}: task ${id} missing text`);
      return { id: `${slug}/${id}`, text: String(t.text) };
    });
    const body = content.trim();
    if (body.length < 80) errors.push(`${slug}: body too short (${body.length} chars)`);
    if (!/biewer tip/i.test(body)) errors.push(`${slug}: body missing "biewer tip" callout`);
    lessons.push({
      slug,
      week: weekNum,
      order: data.order,
      title: String(data.title),
      minutesPerDay: data.minutesPerDay ?? 10,
      body,
      tasks: fullTasks,
    });
  }
  lessons.sort((a, b) => a.order - b.order);
  weeks.push({ week: weekNum, theme: meta.theme, month: meta.month, lessons });
}

weeks.sort((a, b) => a.week - b.week);

const EXPECTED_WEEKS = Object.keys(WEEK_META).length;
if (weeks.length !== EXPECTED_WEEKS)
  errors.push(`expected ${EXPECTED_WEEKS} weeks, found ${weeks.length}`);
for (const w of weeks) {
  if (w.lessons.length !== 4) errors.push(`week ${w.week}: has ${w.lessons.length} lessons (need 4)`);
}

if (errors.length) {
  console.error("course manifest validation FAILED:\n" + errors.map((e) => `  ✗ ${e}`).join("\n"));
  process.exit(1);
}

const totalLessons = weeks.reduce((n, w) => n + w.lessons.length, 0);
const totalTasks = weeks.reduce(
  (n, w) => n + w.lessons.reduce((m, l) => m + l.tasks.length, 0),
  0
);

const manifest = { weeks, totalLessons, totalTasks };

const banner = `// AUTO-GENERATED by scripts/build-manifest.mjs — do not edit by hand.
// Regenerate with: pnpm manifest
import type { CourseManifest } from "./course.js";

export const COURSE_MANIFEST: CourseManifest = `;

fs.writeFileSync(outFile, banner + JSON.stringify(manifest, null, 2) + " as CourseManifest;\n");
console.log(
  `✓ course manifest: ${weeks.length} weeks, ${totalLessons} lessons, ${totalTasks} tasks → src/course-manifest.ts`
);
